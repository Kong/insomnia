// Not a regression check — prints the id/parentId/key coercion surface for eyeballing. Run via
// `npm run sandbox:coercion`.
it('prints the id-like-argument coercion surface', async () => {
  const { pluginToMainAPI } = await import('../templating-worker-database');
  const entries = describeCoercionSurface(pluginToMainAPI);
  const lines = formatCoercionSurfaceEntries(entries);
  console.log(lines.join('\n'));
  console.log(`\n${lines.length} handlers`);
  expect(lines.length).toBeGreaterThan(0);
});
